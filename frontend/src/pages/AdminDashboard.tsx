import React from 'react';
import { useQuery } from '@tanstack/react-query';
import { useNavigate } from 'react-router-dom';
import { getSystemStatistics } from '../api/admin';
import LoadingState from '../components/LoadingState';
import ErrorState from '../components/ErrorState';
import ScoreCard from '../components/ScoreCard';
import { ShieldAlert, Database, Settings, Sparkles, FileText } from 'lucide-react';

const AdminDashboard: React.FC = () => {
  const navigate = useNavigate();

  const { data, isLoading, error, refetch } = useQuery({
    queryKey: ['adminStatistics'],
    queryFn: async () => {
      const response = await getSystemStatistics();
      return response.data;
    }
  });

  if (isLoading) {
    return <LoadingState message="Connecting to administration pipelines..." />;
  }

  if (error) {
    return (
      <ErrorState 
        onRetry={refetch} 
        title="Admin Access Denied"
        message="Verify you have administrative rights and the backend is online." 
      />
    );
  }

  const stats = data;

  return (
    <div className="flex flex-col gap-6">
      {/* Title */}
      <div className="flex justify-between items-center flex-wrap gap-4">
        <div>
          <h1 className="text-2xl font-black text-slate-100 font-sans tracking-wide flex items-center gap-2">
            <ShieldAlert className="w-6 h-6 text-red-500" />
            System Administration
          </h1>
          <p className="text-xs text-slate-400 font-semibold mt-0.5">
            Real-time analytics, user database volumes, and global AI provider switches.
          </p>
        </div>
      </div>

      {stats && (
        <>
          {/* Stats Grid */}
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-6">
            <ScoreCard
              score={stats.totalUsers}
              title="Registered Users"
              subtitle="User accounts database"
              description="Total number of developer/user profiles registered."
            />
            <ScoreCard
              score={stats.totalResumes}
              title="Global Resumes"
              subtitle="Resume document entities"
              description="Cumulative count of all files uploaded and parsed."
            />
            <ScoreCard
              score={stats.totalAnalyses}
              title="AI Analyses Run"
              subtitle="AI execution triggers"
              description="Total resume analyses generated by LLM connectors."
            />
            
            {/* AI Provider configuration card */}
            <div className="glass-panel rounded-2xl p-6 flex flex-col justify-between">
              <div>
                <span className="text-[9px] text-slate-500 font-bold uppercase tracking-wider">Active AI Provider</span>
                <div className="flex items-center gap-2 mt-1">
                  <Sparkles className="w-5 h-5 text-brand-400" />
                  <h3 className="text-base font-black text-slate-100 uppercase">{stats.aiProvider || 'mock'}</h3>
                </div>
                <p className="text-[10px] text-slate-500 leading-normal mt-1">
                  AI provider is configured via the backend's environment setup (Mock, Gemini, or OpenAI).
                </p>
              </div>
              
              <div className="text-[9px] text-slate-400 font-semibold mt-4 pt-2 border-t border-slate-900 flex items-center gap-1">
                <Settings className="w-3.5 h-3.5" />
                Read-only Sandbox Mode
              </div>
            </div>
          </div>

          {/* System Analyses Table */}
          <div className="glass-panel rounded-2xl p-6">
            <h3 className="text-sm font-bold text-slate-100 uppercase tracking-wider mb-4 flex items-center gap-2">
              <Database className="w-4 h-4 text-brand-400" />
              Global System Logs
            </h3>
            
            {stats.recentSystemAnalyses.length === 0 ? (
              <p className="text-xs text-slate-500 italic py-4">No global analyses run yet.</p>
            ) : (
              <div className="overflow-x-auto">
                <table className="w-full text-left text-xs border-collapse">
                  <thead>
                    <tr className="border-b border-slate-800 text-slate-500 uppercase font-bold">
                      <th className="pb-3 pl-4">Analysis ID</th>
                      <th className="pb-3">Resume Name</th>
                      <th className="pb-3">ATS Score</th>
                      <th className="pb-3">Match Score</th>
                      <th className="pb-3">Status</th>
                      <th className="pb-3 pr-4 text-right">Action</th>
                    </tr>
                  </thead>
                  <tbody>
                    {stats.recentSystemAnalyses.map((analysis) => (
                      <tr key={analysis.id} className="border-b border-slate-900 hover:bg-slate-900/20 transition-all font-medium">
                        <td className="py-4 pl-4 text-slate-400 font-mono">
                          {analysis.id.substring(0, 8)}...
                        </td>
                        <td className="py-4">
                          <div className="flex items-center gap-2">
                            <FileText className="w-4 h-4 text-slate-500" />
                            <div>
                              <span className="text-slate-200 block font-bold truncate max-w-[150px]">
                                {analysis.resumeName}
                              </span>
                              <span className="text-[9px] text-slate-500 font-bold uppercase mt-0.5">
                                v{analysis.versionNumber}
                              </span>
                            </div>
                          </div>
                        </td>
                        <td className="py-4 font-bold">
                          {analysis.status === 'COMPLETED' ? (
                            <span className="text-brand-400">{analysis.atsScore}/100</span>
                          ) : (
                            <span className="text-slate-600">—</span>
                          )}
                        </td>
                        <td className="py-4 font-bold">
                          {analysis.status === 'COMPLETED' && analysis.jobMatchScore !== null ? (
                            <span className="text-emerald-400">{analysis.jobMatchScore}%</span>
                          ) : (
                            <span className="text-slate-600">—</span>
                          )}
                        </td>
                        <td className="py-4 font-bold">
                          <span className={`px-2 py-0.5 rounded text-[9px] uppercase ${
                            analysis.status === 'COMPLETED' ? 'bg-emerald-500/10 text-emerald-400 border border-emerald-500/20' :
                            analysis.status === 'FAILED' ? 'bg-rose-500/10 text-rose-400 border border-rose-500/20' :
                            'bg-slate-900 text-slate-500 border border-slate-800 animate-pulse'
                          }`}>
                            {analysis.status}
                          </span>
                        </td>
                        <td className="py-4 pr-4 text-right">
                          <button
                            onClick={() => navigate(`/analysis/${analysis.id}`)}
                            className="glass-btn-secondary py-1 px-3 rounded-lg text-[10px]"
                          >
                            Inspect
                          </button>
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </div>
        </>
      )}
    </div>
  );
};

export default AdminDashboard;
